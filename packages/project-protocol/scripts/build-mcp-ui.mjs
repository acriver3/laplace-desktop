import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";


{
	const root = fileURLToPath(new URL("..", import.meta.url));
	for (const widget of [
        {
            entry: "src/mcp/ui/broker/main.tsx",
            styles: ["../src/mcp/ui/broker/style.css"],
            output: "broker-approval-widget",
            directory: "broker-approval-ui",
            title: "Review credential matches",
        },
		{
			entry: "src/mcp/ui/browser/main.tsx",
			styles: ["../src/mcp/ui/browser/style.css"],
			output: "browser-approval-widget",
			directory: "browser-approval-ui",
			title: "Connect your browser account",
		},
		{
			entry: "src/mcp/ui/main.tsx",
			styles: [
				"../../ui/styles/connect-theme.css",
				"../../ui/components/connector/connection-tile.css",
				"../src/mcp/ui/style.css",
			],
			output: "widget",
			directory: "connect-ui",
			title: "Laplace Home",
		},
		{
			entry: "src/mcp/ui/yc/main.tsx",
			styles: ["../src/mcp/ui/yc/style.css"],
			output: "yc-widget",
			directory: "yc-ui",
			title: "YC application editor",
		},
	]) {
		const result = await build({
			absWorkingDir: root,
			entryPoints: [widget.entry],
			bundle: true,
			write: false,
			minify: true,
			format: "iife",
			platform: "browser",
			target: "es2022",
			jsx: "automatic",
			define: { "process.env.NODE_ENV": '"production"' },
		});
		const script = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
		const css = (
			await Promise.all(
				widget.styles.map((path) => readFile(new URL(path, import.meta.url), "utf8")),
			)
		).join("\n");
		const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${widget.title}</title><style>${css}</style></head><body><div id="root"></div><script>${script}</script></body></html>`;
		await writeFile(
			new URL(`../src/mcp/${widget.output}.ts`, import.meta.url),
			`// Generated by build-mcp-ui.mjs.\nexport default ${JSON.stringify(html)};\n`,
		);
		await mkdir(new URL(`../../../apps/vibesdk/dist/${widget.directory}/`, import.meta.url), {
			recursive: true,
		});
		await writeFile(
			new URL(`../../../apps/vibesdk/dist/${widget.directory}/index.html`, import.meta.url),
			html,
		);
	}
}
